"""L3-A (`import` DAG reachability) + L3-A+ (`import`-constrained single-pass symbol reference chain)."""

from __future__ import annotations

import argparse
import json
import os
import time
from collections import Counter, defaultdict, deque
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

from audit_provenance import sha256_file
from lean_lexer import strip_lean_comments_and_strings
from lean_probes import _ident_used_in_body

PRIORITY_TRACE_RULES = frozenset(
    {
        "DEF_FUN_TRUE",
        "DEF_MULTIARG_FUN_TRUE",
        "DEF_SINGLEARG_FUN_TRUE",
        "DEF_CONST_TRUE",
        "DEF_TRIVIAL_STUB",
        "DEF_EXPLICIT_WILDCARD_PARAM",
    }
)


def compute_reachable(roots: list[str], adj: dict[str, list[str]]) -> set[str]:
    visited: set[str] = set()
    q: deque[str] = deque()
    for r in roots:
        if r in adj and r not in visited:
            visited.add(r)
            q.append(r)
    while q:
        cur = q.popleft()
        for nxt in adj.get(cur, ()):
            if nxt in adj and nxt not in visited:
                visited.add(nxt)
                q.append(nxt)
    return visited


def _scan_importer_batch(args: tuple[str, list[tuple[str, str, list[str]]]]) -> list[tuple[str, list[str]]]:
    """Read each importer file ONCE, prefilter with raw substring, then verify with L1 mask."""
    root_str, items = args
    root_dir = Path(root_str)
    out: list[tuple[str, list[str]]] = []
    for mod, rel_file, syms in items:
        raw = (root_dir / rel_file).read_text(encoding="utf-8", errors="replace")
        cand = [s for s in syms if s in raw]
        if not cand:
            continue
        masked = strip_lean_comments_and_strings(raw)
        matched = [s for s in cand if _ident_used_in_body(s, masked)]
        if matched:
            out.append((mod, matched))
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description="Run L3-A import DAG & L3-A+ symbol reference tracing")
    ap.add_argument("--root", required=True, help="Root src directory containing .lean files")
    ap.add_argument("--dag-index", required=True, help="Path to *_dag_index.json generated by run_audit.py")
    ap.add_argument("--out-dir", required=True, help="Directory for L3 reports")
    ap.add_argument("--prefix", default="full", help="Output filename prefix")
    ap.add_argument("--entry", action="append", default=[], help="Entry module name (repeatable; defaults to Main)")
    ap.add_argument("--entry-config", default="", help="Optional JSON config containing entry_roots list")
    ap.add_argument("--workers", type=int, default=max(1, (os.cpu_count() or 4) - 1))
    ap.add_argument("--l3a-only", action="store_true", help="Run fast L3-A reachability only, skip L3-A+ symbol scan")
    args = ap.parse_args()

    t0 = time.perf_counter()
    root_dir = Path(args.root)
    dag_path = Path(args.dag_index)
    idx_data = json.loads(dag_path.read_text(encoding="utf-8"))
    modules: dict[str, dict] = idx_data["modules"]
    findings: list[dict] = idx_data["findings"]
    upstream_provenance = idx_data.get("provenance", {})

    configured_entries: list[str] = list(args.entry)
    if args.entry_config:
        cfg = json.loads(Path(args.entry_config).read_text(encoding="utf-8"))
        configured_entries.extend(cfg.get("entry_roots", []))
    if not configured_entries:
        configured_entries = ["Main"]
    configured_entries = list(dict.fromkeys(configured_entries))

    adj: dict[str, list[str]] = {}
    rev_adj: dict[str, list[str]] = defaultdict(list)
    for mod, info in modules.items():
        local_imps = list(dict.fromkeys(imp for imp in info["imports"] if imp in modules))
        adj[mod] = local_imps
        for imp in local_imps:
            rev_adj[imp].append(mod)

    entry_roots = [m for m in configured_entries if m in modules]
    primary_root = configured_entries[0]
    reachable_main = compute_reachable([primary_root] if primary_root in modules else entry_roots, adj)
    reachable_all_entries = compute_reachable(entry_roots, adj)

    total_files = len(modules)
    total_code_lines = sum(m["code_lines"] for m in modules.values())
    reach_files = len(reachable_main)
    reach_code_lines = sum(modules[m]["code_lines"] for m in reachable_main)
    dead_files = total_files - reach_files
    dead_code_lines = total_code_lines - reach_code_lines

    dir_stats: dict[str, Counter] = defaultdict(Counter)
    for mod, info in modules.items():
        top = info["file"].split("/", 1)[0] if "/" in info["file"] else "(root)"
        c = dir_stats[top]
        c["total_files"] += 1
        c["total_code_lines"] += info["code_lines"]
        if mod in reachable_main:
            c["reach_files"] += 1
            c["reach_code_lines"] += info["code_lines"]
        else:
            c["dead_files"] += 1
            c["dead_code_lines"] += info["code_lines"]

    rule_reach_counts: dict[str, Counter] = defaultdict(Counter)
    trace_targets: list[dict] = []
    for f in findings:
        r = f["rule"]
        in_reach = f["module"] in reachable_main
        rule_reach_counts[r]["total"] += 1
        if in_reach:
            rule_reach_counts[r]["in_main_cone"] += 1
            if r in PRIORITY_TRACE_RULES:
                trace_targets.append(f)
        else:
            rule_reach_counts[r]["outside_main_cone"] += 1

    t_l3a = time.perf_counter()
    print(
        f"L3-A done in {t_l3a - t0:.2f}s: reachable={reach_files:,}/{total_files:,} "
        f"({reach_files/total_files*100:.2f}%), dead={dead_files:,}, priority_targets_in_cone={len(trace_targets)}",
        flush=True,
    )

    traced_results: list[dict] = []
    if not args.l3a_only:
        mod_to_importers: dict[str, set[str]] = {}
        mod_to_parents: dict[str, dict[str, str]] = {}
        unique_target_mods = {f["module"] for f in trace_targets}

        for tmod in unique_target_mods:
            trans: set[str] = set()
            parents: dict[str, str] = {}
            q: deque[str] = deque([tmod])
            while q:
                cur = q.popleft()
                for imp in rev_adj.get(cur, ()):
                    if imp in reachable_main and imp not in trans and imp != tmod:
                        trans.add(imp)
                        parents[imp] = cur
                        q.append(imp)
            mod_to_importers[tmod] = trans
            mod_to_parents[tmod] = parents

        importer_to_syms: dict[str, set[str]] = defaultdict(set)
        target_short_syms: list[str] = []
        for f in trace_targets:
            short_sym = f["name"].rsplit(".", 1)[-1]
            target_short_syms.append(short_sym)
            if not short_sym or short_sym == "<anonymous>":
                continue
            for imp in mod_to_importers[f["module"]]:
                importer_to_syms[imp].add(short_sym)

        scan_items = [(imp, modules[imp]["file"], sorted(syms)) for imp, syms in importer_to_syms.items()]
        batch_size = max(50, len(scan_items) // (args.workers * 4) + 1)
        batches = [(str(root_dir), scan_items[i : i + batch_size]) for i in range(0, len(scan_items), batch_size)]

        sym_used_in_mods: dict[str, set[str]] = defaultdict(set)
        if batches:
            with ProcessPoolExecutor(max_workers=args.workers) as pool:
                for batch_res in pool.map(_scan_importer_batch, batches):
                    for imp_mod, matched_syms in batch_res:
                        for s in matched_syms:
                            sym_used_in_mods[s].add(imp_mod)

        entry_set = set(entry_roots)
        for f, short_sym in zip(trace_targets, target_short_syms):
            tmod = f["module"]
            direct_importers = [m for m in rev_adj.get(tmod, ()) if m in reachable_main]
            trans_importers = mod_to_importers[tmod]
            parents = mod_to_parents[tmod]

            used_set = sym_used_in_mods.get(short_sym, set())
            direct_hits = [m for m in direct_importers if m in used_set]
            trans_hits = sorted(m for m in trans_importers if m in used_set)

            sample_paths: list[list[str]] = []
            for hm in trans_hits[:5]:
                chain = [hm]
                cur = hm
                while cur in parents:
                    cur = parents[cur]
                    chain.append(cur)
                chain.reverse()
                sample_paths.append(chain)

            status = (
                "DIRECT_AND_TRANSITIVE_REFS"
                if direct_hits
                else ("TRANSITIVE_ONLY_REFS" if trans_hits else "NO_SYMBOL_REF_IN_CONE")
            )
            traced_results.append(
                {
                    **f,
                    "l3a_plus": {
                        "direct_reachable_importers": len(direct_importers),
                        "transitive_reachable_importers": len(trans_importers),
                        "direct_symbol_refs": len(direct_hits),
                        "transitive_symbol_refs": len(trans_hits),
                        "direct_ref_to_entry": any(m in entry_set for m in trans_hits),
                        "sample_import_chains": sample_paths,
                        "status": status,
                    },
                }
            )

    # PG-05 Conservation invariants
    assert reach_files + dead_files == total_files, "reachable + dead != total_files"
    assert reach_code_lines + dead_code_lines == total_code_lines, "reachable_lines + dead_lines != total"
    assert sum(c["total_files"] for c in dir_stats.values()) == total_files, "dir_stats files mismatch"
    for r, c in rule_reach_counts.items():
        assert c["in_main_cone"] + c["outside_main_cone"] == c["total"], f"cone split mismatch for {r}"

    elapsed = time.perf_counter() - t0
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    summary = {
        "timing_sec": round(elapsed, 2),
        "provenance": {
            "dag_index_name": dag_path.name,
            "lean_dag_sha256": sha256_file(Path(__file__)),
            "upstream_provenance": upstream_provenance,
        },
        "invariants_checked": {
            "reach_plus_dead_files": True,
            "reach_plus_dead_code_lines": True,
            "dir_stats_files_conservation": True,
            "findings_cone_split_conservation": True,
        },
        "l3a_plus_caveat": "Short-symbol lookup can collide with local bindings or homonymous defs; treat L3-A+ counts as candidate leads and cite only manually verified full chains.",
        "entry_roots": entry_roots,
        "reachability_main": {
            "total_files": total_files,
            "reachable_files": reach_files,
            "reachable_files_pct": round(reach_files / total_files * 100, 2) if total_files else 0.0,
            "dead_files": dead_files,
            "dead_files_pct": round(dead_files / total_files * 100, 2) if total_files else 0.0,
            "total_code_lines": total_code_lines,
            "reachable_code_lines": reach_code_lines,
            "reachable_code_lines_pct": round(reach_code_lines / total_code_lines * 100, 2) if total_code_lines else 0.0,
            "dead_code_lines": dead_code_lines,
            "dead_code_lines_pct": round(dead_code_lines / total_code_lines * 100, 2) if total_code_lines else 0.0,
            "reachable_all_entries_files": len(reachable_all_entries),
        },
        "by_top_dir": {k: dict(v) for k, v in sorted(dir_stats.items())},
        "findings_cone_split": {k: dict(v) for k, v in sorted(rule_reach_counts.items())},
        "l3a_plus_traced": traced_results,
    }

    json_path = out_dir / f"{args.prefix}_l3_dag.json"
    json_path.write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")

    md = [
        f"# Lean 4 Import DAG & Reachability Report ({args.prefix})",
        "",
        f"- **Elapsed**: `{elapsed:.2f}s` | **Primary Entry**: `{primary_root}` (`entry_roots={entry_roots}`)",
        f"- **Total Project Files**: `{total_files:,}` | **Reachable**: `{reach_files:,}` (`{summary['reachability_main']['reachable_files_pct']}%`) | **Unimported**: `{dead_files:,}` (`{summary['reachability_main']['dead_files_pct']}%`)",
        f"- **Total Code Lines**: `{total_code_lines:,}` | **Reachable**: `{reach_code_lines:,}` (`{summary['reachability_main']['reachable_code_lines_pct']}%`) | **Unimported**: `{dead_code_lines:,}` (`{summary['reachability_main']['dead_code_lines_pct']}%`)",
        "",
        "## 1. Reachability by Top-Level Module",
        "",
        "| Top Dir | Total Files | Reachable Files | Unimported Files | Total Code Lines | Unimported Lines | Unimported % |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for top in sorted(dir_stats):
        c = dir_stats[top]
        dp = (c["dead_code_lines"] / c["total_code_lines"] * 100) if c["total_code_lines"] else 0.0
        md.append(
            f"| `{top}` | {c['total_files']:,} | {c['reach_files']:,} | {c['dead_files']:,} | {c['total_code_lines']:,} | {c['dead_code_lines']:,} | {dp:.2f}% |"
        )

    md.extend(["", "## 2. Definition-Layer Pattern Findings: Inside Entry Cone vs Outside Cone", "", "| Rule | Total | In Entry Cone | Outside Cone |", "|---|---:|---:|---:|"])
    for r in sorted(rule_reach_counts):
        c = rule_reach_counts[r]
        md.append(f"| `{r}` | {c['total']:,} | {c['in_main_cone']:,} | {c['outside_main_cone']:,} |")

    if not args.l3a_only and traced_results:
        md.extend(["", "## 3. L3-A+ Candidate Symbol Reference Audit (Inside Entry Cone)", ""])
        for item in traced_results[:60]:
            tr = item["l3a_plus"]
            md.append(
                f"- `[{item['rule']}]` `{item['file']}:{item['line']}` (`{item['name']}`) -> **{tr['status']}** "
                f"(direct_importers={tr['direct_reachable_importers']}, direct_refs={tr['direct_symbol_refs']}, trans_refs={tr['transitive_symbol_refs']})"
            )

    md_path = out_dir / f"{args.prefix}_l3_dag.md"
    md_path.write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"DONE L3 DAG in {elapsed:.2f}s -> {md_path}", flush=True)


if __name__ == "__main__":
    main()
